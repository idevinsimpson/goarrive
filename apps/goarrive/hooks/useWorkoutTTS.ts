// Constructor helper. `new Audio(url)` sets src synchronously, which is too
// late for crossOrigin — MediaElementAudioSourceNode would taint the graph
// and produce silence. This helper enforces the correct order:
//   Audio() → crossOrigin='anonymous' → src → wire to gain.
function createManagedAudio(url?: string): HTMLAudioElement {
  const audio: HTMLAudioElement = new (window as any).Audio();
  try { (audio as any).crossOrigin = 'anonymous'; } catch {}
  if (url) audio.src = url;
  applyVoiceVolume(audio);
  return audio;
}

// Drop every pooled element. Called when the player unmounts: pooled elements
// frozen mid-clip survive unmount (module-level pool), and on the next player
// session iOS Safari can resolve play() on a wedged element without actually
// playing, leaving all audio silent. Pooling WITHIN a single player session
// must stay — see the comment above. Also drops the blessed generic players
// and re-arms unlockAudioPlayback so the next Start tap rebuilds everything
// from scratch inside a fresh user gesture, exactly like a first session.
export function resetAudioPool(): void {
  for (const key of Object.keys(audioPool)) {
    try {
      audioPool[key].pause();
      audioPool[key].removeAttribute('src');
    } catch {}
    delete audioPool[key];
  }
  for (const el of blessedGenericPlayers) {
    try {
      el.pause();
      el.removeAttribute('src');
    } catch {}
  }
  blessedGenericPlayers.length = 0;
  audioUnlocked = false;
  stopKeepalive();
  stopGraphKeepalive();
  try { mediaStreamDest?.disconnect(); } catch {}
  mediaStreamDest = null;
}

function poolKeyForCue(key: CueKey): string {
  return `cue:${key}`;
}
function poolKeyForVoice(url: string): string {
  return `voice:${url}`;
}

function preloadCue(key: CueKey): void {
  if (Platform.OS !== 'web') return;
  if (typeof window === 'undefined') return;
  const poolKey = poolKeyForCue(key);
  if (audioPool[poolKey]) return;
  try {
    const audio = createManagedAudio(CUES[key]);
    audio.preload = 'auto';
    audioPool[poolKey] = audio;
  } catch {
    // Audio API unavailable
  }
}

